export function learnerInitials(name: string) {
  return name
    .split(/\s+/)
    .filter(Boolean)
    .map((p) => p[0])
    .join('')
    .slice(0, 2)
    .toUpperCase()
}

export function nextLearnerColor(index: number) {
  return LEARNER_COLORS[index % LEARNER_COLORS.length]
}

